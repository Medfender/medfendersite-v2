// ── Featured-artists ingestion generator ────────────────────────────────────
// Scans public/audio/featured-artists/ + public/images/Thumbnails/, pairs
// files by basename, and writes a generated FeaturedTrack[] to
// src/data/generated/featuredArtists.gen.ts.
//
// Usage:  npx tsx scripts/generate-featured-artists.ts
// Run it manually after adding a track, or wire it into the
// `watch:featured` script for continuous watching.
//
// Hand-written metadata overrides live in src/data/trackList.ts — entries
// there take precedence over generated entries by id.

import * as fs from "node:fs";
import * as path from "node:path";
import { FeaturedTrack } from "../src/data/featuredTrackTypes";

const ROOT = path.resolve(__dirname, "..");
const AUDIO_DIR = path.join(ROOT, "public", "audio", "featured-artists");
const THUMB_DIR = path.join(ROOT, "public", "images", "Thumbnails");
const OUT_FILE = path.join(ROOT, "src", "data", "generated", "featuredArtists.gen.ts");

const AUDIO_EXTS = new Set([".mp3", ".wav", ".flac", ".m4a", ".ogg", ".aac"]);
const IMAGE_EXTS = new Set([".jpg", ".jpeg", ".webp", ".png", ".gif", ".bmp"]);

// ── Filename parsing ───────────────────────────────────────────────────────
// Basename → { name, artist }. Tries a few common separators; falls back to
// the whole title with artist = "".
function parseName(raw: string): { name: string; artist: string } {
  let s = raw.trim();
  s = s.replace(/\s*[-–—]\s*\(.*?\)\s*$/, "").trim();
  s = s.replace(/\s*[-–—]\s*\(ORIGINAL\)\s*$/i, "").trim();
  // "Artist - Title" or "Title - Artist"
  const dash = s.match(/^(.+?)\s+-\s+(.+)$/);
  if (dash) {
    const a = dash[1].trim();
    const b = dash[2].trim();
    // Heuristic: if the second part contains "feat." it's the artist.
    if (/feat\b/i.test(b)) return { name: a, artist: b };
    if (/feat\b/i.test(a)) return { name: b, artist: a };
    // Default: "Artist - Title" (first = artist).
    return { name: b, artist: a };
  }
  // "Title feat. Artist"
  const feat = s.match(/^(.+?)\s+feat\.?\s+(.+)$/i);
  if (feat) return { name: feat[1].trim(), artist: `feat. ${feat[2].trim()}` };
  return { name: s, artist: "" };
}

function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

function readDir(dir: string): string[] {
  try {
    return fs.readdirSync(dir).filter((f) => !f.startsWith("."));
  } catch {
    return [];
  }
}

function main() {
  const audios = readDir(AUDIO_DIR).filter((f) =>
    AUDIO_EXTS.has(path.extname(f).toLowerCase()),
  );
  const images = readDir(THUMB_DIR).filter((f) =>
    IMAGE_EXTS.has(path.extname(f).toLowerCase()),
  );

  // basename → image filename (first match wins)
  const thumbByBase = new Map<string, string>();
  for (const img of images) {
    const base = path.basename(img, path.extname(img));
    if (!thumbByBase.has(base)) thumbByBase.set(base, img);
  }

  const tracks: FeaturedTrack[] = [];
  for (const audio of audios) {
    const base = path.basename(audio, path.extname(audio));
    const { name, artist } = parseName(base);
    const thumb = thumbByBase.get(base);
    tracks.push({
      id: slugify(base),
      name,
      artist,
      gearTag: "TONEX",
      audioUrl: `/audio/featured-artists/${encodeURIComponent(audio)}`,
      thumbnail: thumb ? `/images/Thumbnails/${encodeURIComponent(thumb)}` : undefined,
      hardware: "TONEX",
    });
  }

  // Deterministic order by name for stable diffs.
  tracks.sort((a, b) => a.name.localeCompare(b.name));

  const lines: string[] = [];
  lines.push("// ── AUTO-GENERATED featured artists ─────────────────────────────────");
  lines.push("// Generated by scripts/generate-featured-artists.ts from");
  lines.push("// public/audio/featured-artists/ + public/images/Thumbnails/. DO NOT EDIT.");
  lines.push("// Hand-written overrides: src/data/trackList.ts (by id).");
  lines.push(`// Last generated: ${new Date().toISOString()}`);
  lines.push(`// Tracks found: ${tracks.length}`);
  lines.push("import { FeaturedTrack } from \"../featuredTrackTypes\";");
  lines.push("");
  lines.push("export const featuredArtists: FeaturedTrack[] = [");
  for (const t of tracks) {
    lines.push("  {");
    lines.push(`    id: ${JSON.stringify(t.id)},`);
    lines.push(`    name: ${JSON.stringify(t.name)},`);
    lines.push(`    artist: ${JSON.stringify(t.artist)},`);
    lines.push(`    gearTag: ${JSON.stringify(t.gearTag)},`);
    lines.push(`    audioUrl: ${JSON.stringify(t.audioUrl)},`);
    lines.push(`    thumbnail: ${t.thumbnail ? JSON.stringify(t.thumbnail) : "undefined"},`);
    lines.push(`    hardware: ${JSON.stringify(t.hardware)},`);
    lines.push("  },");
  }
  lines.push("];");

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, lines.join("\n") + "\n", "utf8");
  console.log(`Wrote ${OUT_FILE} with ${tracks.length} track(s).`);
  for (const t of tracks) console.log(`  - ${t.name} (${t.artist}) → ${t.audioUrl}`);
}

main();